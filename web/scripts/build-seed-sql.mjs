// Writes supabase/seed.sql from src/data/content.json: one SQL file anyone can paste into the
// Supabase SQL Editor (after the migrations) to load or refresh the playbook content. No keys needed.
// It upserts, so it's safe to run again after content changes. Re-generate after editing content.json:
//   node scripts/build-seed-sql.mjs
import fs from "node:fs";
import { content, contentRows, jsonColumns, keys } from "./content-rows.mjs";

const str = (v) => `'${String(v).replace(/'/g, "''")}'`;
function literal(table, column, v) {
  if (v === null || v === undefined) return "null";
  if ((jsonColumns[table] || []).includes(column)) return `${str(JSON.stringify(v))}::jsonb`;
  if (Array.isArray(v)) return v.length ? `array[${v.map(str).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  return str(v);
}

const c = content();
let sql = `-- Playbook content for AI Playbook for Schools.
-- Generated by web/scripts/build-seed-sql.mjs from web/src/data/content.json. Do not edit by hand.
-- Run it in the Supabase SQL Editor after the migrations in web/supabase/migrations/.
-- Safe to run again: existing rows are updated, nothing is deleted. Admin settings such as reward
-- days are not touched (only "checked_on", "ease_labels" and "example_role_badges" are set).

begin;
`;
for (const [table, rows] of contentRows(c)) {
  const cols = Object.keys(rows[0]);
  const pk = keys[table] || ["id"];
  const updates = cols.filter((col) => !pk.includes(col)).map((col) => `${col} = excluded.${col}`).join(", ");
  sql += `\n-- ${table} (${rows.length})\ninsert into public.${table} (${cols.join(", ")}) values\n`;
  sql += rows.map((r) => `  (${cols.map((col) => literal(table, col, r[col])).join(", ")})`).join(",\n");
  sql += `\non conflict (${pk.join(", ")}) do update set ${updates};\n`;
}
sql += "\ncommit;\n";
fs.writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`wrote supabase/seed.sql (${(sql.length / 1024).toFixed(0)} KB)`);
